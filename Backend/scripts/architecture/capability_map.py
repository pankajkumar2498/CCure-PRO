def _third_party(path: Path) -> set[str]:
    tree = _tree(path)
    inside: set[int] = set()
    for node in ast.walk(tree):
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
            inside.update(id(child) for child in ast.walk(node))
    found = set()
    for node in ast.walk(tree):
        if id(node) in inside:
            continue
        names = []
        if isinstance(node, ast.Import):
            names = [alias.name for alias in node.names]
        elif isinstance(node, ast.ImportFrom) and not node.level and node.module:
            names = [node.module]
        for name in names:
            if name.split(".")[0] in HEAVY:
                found.add(name.split(".")[0])
    return found


def load_profiles(modules, raw_edges) -> dict[str, dict[str, list[str]]]:
    """Entry -> the capabilities (other than its own) and heavy packages its
    top-level imports load, transitively, as importing it would."""
    adjacency: dict[str, set[str]] = defaultdict(set)
    for edge in raw_edges:
        if not edge.lazy:
            adjacency[edge.src].add(edge.dst)

    def with_parents(module: str) -> list[str]:
        parts = module.split(".")
        return [
            ".".join(parts[:i])
            for i in range(1, len(parts) + 1)
            if ".".join(parts[:i]) in modules
        ]

    third_party_cache: dict[str, set[str]] = {}
    profiles = {}
    for entry in ENTRY_POINTS:
        if entry not in modules:
            continue
        seen = set(with_parents(entry))
        stack = list(seen)
        while stack:
            current = stack.pop()
            for target in adjacency.get(current, ()):
                for module in with_parents(target):
                    if module not in seen:
                        seen.add(module)
                        stack.append(module)
        own = capability_of(entry)
        heavy = set()
        for module in seen:
            if module not in third_party_cache:
                third_party_cache[module] = _third_party(modules[module])
            heavy |= third_party_cache[module]
        profiles[entry] = {
            "capabilities": sorted({capability_of(m) for m in seen} - {own}),
            "third_party": sorted(heavy),
        }
    return profiles


# ── Measurement, baseline and ratchet ─────────────────────────────────────────
def measure(root: Path = BACKEND_ROOT) -> dict:
    modules, raw_edges = collect_edges(root)
    missing = unmapped_modules(modules)
    if missing:
        return {"unmapped": missing}
    _, edges = capability_edges(root, graph=(modules, raw_edges))
    upward, lateral = directional_edges(edges)
    references, writes = table_access(modules, root)
    cross = list(_cross(edges))
    return {
        "unmapped": [],
        "modules": len(modules),
        "cross_capability_imports": {
            "top_level": sum(1 for e, _, _ in cross if not e.lazy),
            "lazy": sum(1 for e, _, _ in cross if e.lazy),
        },
        "cycles": [sorted(c) for c in capability_cycles(edges)],
        "cycles_top_level": [
            sorted(c) for c in capability_cycles(edges, top_level_only=True)
        ],
        "upward_edges": sorted(upward),
        "lateral_edges": sorted(lateral),
        "foreign_table_references": sorted(references),
        "foreign_table_writes": sorted(writes),
        "load_profiles": load_profiles(modules, raw_edges),
    }


#: The figures measured when the ratchet was introduced (16 Oct 2026, branch
#: refactor/modular-architecture after Phase 0). They may only be lowered: a
#: baseline larger than any of them is refused, so regenerating the baseline
#: cannot admit new coupling. Lowering one is how progress is locked in.
CEILINGS = {
    "largest_cycle": 22,
    "largest_cycle_top_level": 13,
    # 50 when introduced; B1 (the limiter from core.rate_limiter) removed 7;
    # B2 (engine ports, the web-scan settler in core.web) removed 3.
    "upward_edges": 40,
    "lateral_edges": 74,
    # 80 when introduced; B2 moved the web_scans settler out of scans.
    "foreign_table_references": 79,
    "foreign_table_writes": 17,
}

_BASELINE_KEYS = (
    "cycles",
    "cycles_top_level",
    "upward_edges",
    "lateral_edges",
    "foreign_table_references",
    "foreign_table_writes",
    "load_profiles",
)


def baseline_from(measurement: dict) -> dict:
    return {key: measurement[key] for key in _BASELINE_KEYS}


def load_baseline(path: Path = BASELINE_FILE) -> dict:
    data = json.loads(path.read_text(encoding="utf-8"))
    return {key: data[key] for key in _BASELINE_KEYS}


def _as_set(rows) -> set:
    return {tuple(row) for row in rows}


def ceiling_problems(baseline: dict) -> list[str]:
    sizes = {
        "largest_cycle": max((len(c) for c in baseline["cycles"]), default=0),
        "largest_cycle_top_level": max(
            (len(c) for c in baseline["cycles_top_level"]), default=0
        ),
        "upward_edges": len(baseline["upward_edges"]),
        "lateral_edges": len(baseline["lateral_edges"]),
        "foreign_table_references": len(baseline["foreign_table_references"]),
        "foreign_table_writes": len(baseline["foreign_table_writes"]),
    }
    return [
        f"the baseline's {name} ({size}) exceeds its ceiling ({CEILINGS[name]}); "
        "the ceilings only ever fall"
        for name, size in sizes.items()
        if size > CEILINGS[name]
    ]


def ratchet_problems(measurement: dict | None = None, baseline=None) -> list[str]:
    """Every way the current tree differs from the baseline, in both directions."""
    measurement = measurement if measurement is not None else measure()
    if measurement["unmapped"]:
        return [
            f"module belongs to no capability — add it to PREFIXES in "
            f"scripts/architecture/capability_map.py: {m}"
            for m in measurement["unmapped"]
        ]
    baseline = baseline if baseline is not None else load_baseline()
    problems = ceiling_problems(baseline)

    for key, label in (("cycles", "cycle"), ("cycles_top_level", "top-level cycle")):
        known = [frozenset(c) for c in baseline[key]]
        current = [frozenset(c) for c in measurement[key]]
        for cycle in current:
            if not any(cycle <= k for k in known):
                problems.append(
                    f"new or enlarged capability {label}: " + ", ".join(sorted(cycle))
                )
        for cycle in known:
            if cycle not in current:
                problems.append(
                    f"recorded capability {label} changed — rewrite the baseline "
                    f"(--write-baseline) and lower CEILINGS: "
                    + ", ".join(sorted(cycle))
                )

    for key, label in (
        ("upward_edges", "upward edge (a lower layer importing a higher one)"),
        ("lateral_edges", "lateral edge (between two capabilities of one layer)"),
        ("foreign_table_references", "reference to another capability's table"),
        ("foreign_table_writes", "write to another capability's table"),
    ):
        known, current = _as_set(baseline[key]), _as_set(measurement[key])
        problems += [f"new {label}: {a} -> {b}" for a, b in sorted(current - known)]
        problems += [
            f"gone — remove it from the baseline (--write-baseline) and lower "
            f"CEILINGS: {label}: {a} -> {b}"
            for a, b in sorted(known - current)
        ]

    for entry, now in sorted(measurement["load_profiles"].items()):
        then = baseline["load_profiles"].get(entry)
        if then is None:
            problems.append(f"no recorded load profile for {entry}")
            continue
        for field in ("capabilities", "third_party"):
            gained = sorted(set(now[field]) - set(then[field]))
            lost = sorted(set(then[field]) - set(now[field]))
            if gained:
                problems.append(f"importing {entry} now also loads {field} {gained}")
            if lost:
                problems.append(
                    f"importing {entry} no longer loads {field} {lost} — "
                    "rewrite the baseline to lock that in"
                )
    for entry in sorted(
        set(baseline["load_profiles"]) - set(measurement["load_profiles"])
    ):
        problems.append(f"recorded load profile has no entry point any more: {entry}")
    return problems


def write_baseline(measurement: dict, path: Path = BASELINE_FILE) -> None:
    data = {
        "_comment": (
            "Generated by `python -m scripts.architecture.capability_map "
            "--write-baseline`. Every entry is existing coupling, recorded so it "
            "cannot grow; read the diff before committing a rewrite. Its sizes "
            "are capped by CEILINGS in capability_map.py, which only ever fall."
        ),
        **baseline_from(measurement),
    }
    path.write_text(json.dumps(data, indent=1, sort_keys=True) + "\n", encoding="utf-8")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[1])
    group = parser.add_mutually_exclusive_group()
    group.add_argument("--json", action="store_true", help="print every measurement")
    group.add_argument("--check", action="store_true", help="exit 1 on a breach")
    group.add_argument(
        "--write-baseline", action="store_true", help="rewrite the baseline file"
    )
    args = parser.parse_args(argv)

    measurement = measure()
    if measurement["unmapped"] and not args.json:
        for module in measurement["unmapped"]:
            print(f"unmapped: {module}")
        return 1
    if args.json:
        json.dump(measurement, sys.stdout, indent=1, sort_keys=True)
        print()
        return 0
    if args.write_baseline:
        problems = ceiling_problems(baseline_from(measurement))
        if problems:
            print("\n".join(problems))
            return 1
        write_baseline(measurement)
        print(f"wrote {BASELINE_FILE}")
        return 0
    if args.check:
        problems = ratchet_problems(measurement)
        print("\n".join(problems) if problems else "capability ratchet holds")
        return 1 if problems else 0

    print(f"modules {measurement['modules']}")
    cross = measurement["cross_capability_imports"]
    print(
        f"cross-capability imports: {cross['top_level']} top-level, {cross['lazy']} lazy"
    )
    for label, key in (
        ("all imports", "cycles"),
        ("top-level only", "cycles_top_level"),
    ):
        sizes = [len(c) for c in measurement[key]]
        print(f"capability cycles ({label}): {sizes}")
    for key in (
        "upward_edges",
        "lateral_edges",
        "foreign_table_references",
        "foreign_table_writes",
    ):
        print(f"{key.replace('_', ' ')}: {len(measurement[key])}")
    return 0


if __name__ == "__main__":  # pragma: no cover
    raise SystemExit(main())
