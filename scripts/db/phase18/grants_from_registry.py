#!/usr/bin/env python3
"""Emit generated_grants.sql from Backend/scripts/architecture/table_ownership.yaml.

    python3 scripts/db/phase18/grants_from_registry.py > scripts/db/phase18/generated_grants.sql

Pure text generation: connects to nothing, reads one YAML file. The grants are
DML only (SELECT, INSERT, UPDATE, DELETE) on the owning module's tables and
USAGE, SELECT, UPDATE on their sequences. A module role is granted nothing on a
table another module owns.

Open question the rehearsal must answer before this is applied (Phase 18 doc,
section 5): Audit's tables carry foreign keys to users and organizations. Whether
INSERTs into them need REFERENCES / SELECT on those platform tables for the
connecting role is settled by running it, not by assuming it.
"""
from __future__ import annotations

import sys
from pathlib import Path

import yaml

REGISTRY = Path(__file__).resolve().parents[3] / "Backend/scripts/architecture/table_ownership.yaml"
ROLE = {
    "platform": "ccure_platform_app",
    "audit": "ccure_audit_app",
    "policy_pro": "ccure_policy_app",
    "rank": "ccure_rank_app",
}
SCHEMA = {"platform": "public", "audit": "public", "policy_pro": "policy_pro", "rank": "rank"}


def main() -> int:
    tables = yaml.safe_load(REGISTRY.read_text())["tables"]
    print("-- GENERATED by grants_from_registry.py from table_ownership.yaml. Do not edit.")
    for name, spec in sorted(tables.items()):
        owner = spec["owner"]
        if owner not in ROLE:  # ir: a separate service, its own database
            continue
        t = f'{SCHEMA[owner]}."{name}"'
        print(f"GRANT SELECT, INSERT, UPDATE, DELETE ON {t} TO {ROLE[owner]};")
        # Sequences owned by the table's own columns (serial / identity), found in
        # the catalogue at run time: a schema shared by two modules (public) cannot
        # be granted "all sequences" without crossing the line.
        print(
            "DO $$ DECLARE s regclass; BEGIN "
            "FOR s IN SELECT d.objid::regclass FROM pg_depend d "
            "JOIN pg_class c ON c.oid = d.objid AND c.relkind = 'S' "
            f"WHERE d.refobjid = '{t}'::regclass AND d.deptype IN ('a','i') LOOP "
            f"EXECUTE format('GRANT USAGE, SELECT, UPDATE ON SEQUENCE %s TO {ROLE[owner]}', s); "
            "END LOOP; END $$;"
        )
    return 0


if __name__ == "__main__":
    sys.exit(main())
