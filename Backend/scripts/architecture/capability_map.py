class UnmappedModule(Exception):
    pass


def capability_of(module: str) -> str:
    """The capability *module* belongs to. ``file:Class`` names a model class,
    which belongs to the capability owning its table."""
    if ":" in module:
        _, class_name = module.split(":", 1)
        table = _class_tables().get(class_name, (None, None))[0]
        owner = table_owners().get(table)
        if owner is None:
            raise UnmappedModule(module)
        return owner
    if module in PACKAGE_ONLY:
        return PACKAGE_ONLY[module]
    parts = module.split(".")
    for i in range(len(parts), 0, -1):
        prefix = ".".join(parts[:i])
        if prefix in PREFIXES:
            return PREFIXES[prefix]
    raise UnmappedModule(module)


def unmapped_modules(modules) -> list[str]:
    missing = []
    for module in modules:
        try:
            capability_of(module)
        except UnmappedModule:
            missing.append(module)
    return sorted(missing)


# ── Tables, their owners, and the model classes that map them ────────────────
#: table_ownership.yaml's ``capability`` vocabulary -> the capabilities above.
OWNERSHIP_CAPABILITY = {
    "identity": "platform",
    "tenancy": "platform",
    "rbac": "platform",
    "audit_log": "platform",
    "notifications": "platform",
}

_OWNERSHIP_LINE = re.compile(
    r"^\s+([a-z0-9_]+):\s*\{owner:\s*([a-z_]+),\s*capability:\s*([a-z_]+)\}\s*$"
)


@lru_cache(maxsize=None)
def table_owners(path: Path = OWNERSHIP_FILE) -> dict[str, str]:
    """
    table -> owning capability, from ``table_ownership.yaml``. Parsed with a
    regular expression over its one-line flow mappings so this stays standard
    library only; ``tests/repo/test_capability_ratchet.py`` asserts the parse
    equals ``yaml.safe_load``.
    """
    owners = {}
    for line in path.read_text(encoding="utf-8").splitlines():
        match = _OWNERSHIP_LINE.match(line)
        if match:
            table, _owner, capability = match.groups()
            owners[table] = OWNERSHIP_CAPABILITY.get(capability, capability)
    return owners


_MODEL_DIRS = ("db/models", "ccure_platform/models")


def model_classes(root: Path = BACKEND_ROOT) -> dict[str, str]:
    """Model class name -> table, for every model file."""
    return {name: table for name, (table, _) in _class_tables(root).items()}


@lru_cache(maxsize=None)
def _class_tables(root: Path = BACKEND_ROOT) -> dict[str, tuple[str, str]]:
    """Model class name -> (table, the module defining it)."""
    classes = {}
    for directory in _MODEL_DIRS:
        for path in sorted((root / directory).glob("*.py")):
            module = ".".join(path.relative_to(root).with_suffix("").parts)
            tree = _tree(path)
            for node in tree.body:
                if not isinstance(node, ast.ClassDef):
                    continue
                for stmt in node.body:
                    if (
                        isinstance(stmt, ast.Assign)
                        and any(
                            isinstance(t, ast.Name) and t.id == "__tablename__"
                            for t in stmt.targets
                        )
                        and isinstance(stmt.value, ast.Constant)
                    ):
                        classes[node.name] = (stmt.value.value, module)
    return classes


# ── The capability graph ─────────────────────────────────────────────────────
_MODEL_PACKAGES = (MODEL_REGISTRY, "ccure_platform.models")


def _is_model_module(module: str) -> bool:
    return any(module == p or module.startswith(p + ".") for p in _MODEL_PACKAGES)


def _resolve_from(module: str, path: Path, node: ast.ImportFrom) -> str:
    """The absolute module an ``ImportFrom`` names, as import_graph resolves it."""
    if not node.level:
        return node.module or ""
    package = module if path.name == "__init__.py" else module.rpartition(".")[0]
    anchor = package.split(".") if package else []
    if node.level > 1:
        anchor = anchor[: len(anchor) - (node.level - 1)]
    return ".".join(anchor + ([node.module] if node.module else []))


def capability_edges(root: Path = BACKEND_ROOT, graph=None):
    """
    ``(modules, edges)`` with model imports attributed precisely.

    * ``db.models`` is a registry that re-exports every model, so its own
      fan-out to the model files is nobody's dependency and is dropped.
    * Every name imported from a model module becomes its own edge: a model
      class to ``file:Class`` — which belongs to the capability owning that
      class's table, so ``from db.models import Scan`` depends on scans, and
      ``ComplianceCredential`` on the credential vault although its class sits
      in the compliance model file — and anything else (a constant, a helper)
      to the file that defines it.
    """
    modules, edges = graph if graph is not None else collect_edges(root)
    classes = _class_tables(root)

    replaced: set[tuple[str, str]] = set()
    named: dict[tuple[str, str], bool] = {}
    for module, path in modules.items():
        if module == MODEL_REGISTRY:
            continue  # the registry's own re-exports are nobody's dependency
        tree = _tree(path)
        inside: set[int] = set()
        for node in ast.walk(tree):
            if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
                inside.update(id(child) for child in ast.walk(node))
        for node in ast.walk(tree):
            if not isinstance(node, ast.ImportFrom):
                continue
            source_module = _resolve_from(module, path, node)
            if not _is_model_module(source_module) or source_module not in modules:
                continue
            replaced.add((module, source_module))
            lazy = id(node) in inside
            for alias in node.names:
                if alias.name in classes:
                    _, defining = classes[alias.name]
                    target = f"{defining}:{alias.name}"
                elif source_module != MODEL_REGISTRY:
                    target = source_module
                else:
                    continue  # a helper re-exported by the registry
                if target.split(":")[0] == module:
                    continue
                key = (module, target)
                named[key] = named.get(key, True) and lazy

    kept = [
        e for e in edges if e.src != MODEL_REGISTRY and (e.src, e.dst) not in replaced
    ]
    kept += [Edge(src, dst, lazy) for (src, dst), lazy in sorted(named.items())]
    return modules, kept


def _cross(edges):
    """Edges whose two ends belong to different capabilities."""
    for edge in edges:
        a, b = capability_of(edge.src), capability_of(edge.dst)
        if a != b:
            yield edge, a, b


def capability_cycles(edges, *, top_level_only: bool = False) -> list[frozenset]:
    graph: dict[str, set[str]] = defaultdict(set)
    for edge, a, b in _cross(edges):
        if top_level_only and edge.lazy:
            continue
        graph[a].add(b)
    for cap in CAPABILITIES:
        graph.setdefault(cap, set())
    return sorted(strongly_connected(graph), key=lambda s: (-len(s), sorted(s)))


def directional_edges(edges) -> tuple[set, set]:
    """``(upward, lateral)`` as sets of ``(src_module, dst_module)``."""
    upward, lateral = set(), set()
    for edge, a, b in _cross(edges):
        la, lb = CAPABILITIES[a][0], CAPABILITIES[b][0]
        if lb > la:
            upward.add((edge.src, edge.dst))
        elif lb == la and la not in SHARED_LAYERS:
            lateral.add((edge.src, edge.dst))
    return upward, lateral


# ── Tables touched outside their owner ────────────────────────────────────────
_WRITE_FUNCTIONS = frozenset({"insert", "update", "delete"})
#: A table named after a SQL keyword in a string literal: one pass per module,
#: the names then filtered to the tables the ownership registry knows.
_SQL = re.compile(
    r"\b(?:FROM|JOIN|UPDATE|INTO|DELETE\s+FROM|TABLE)\s+\"?(?:public\.)?([a-z_][a-z0-9_]*)\b",
    re.I,
)


def table_access(modules, root: Path = BACKEND_ROOT) -> tuple[set, set]:
    """
    ``(references, writes)`` as sets of ``(capability, table)`` for tables
    owned by another capability. Platform tables are left out: module code
    reaches identity through ``ccure_platform.api``, and the identity ratchet
    counts what remains.
    """
    classes = model_classes(root)
    owners = table_owners()
    references, writes = set(), set()
    for module, path in modules.items():
        cap = capability_of(module)
        tree = _tree(path)
        local: dict[str, str] = {}
        for node in ast.walk(tree):
            if (
                isinstance(node, ast.ImportFrom)
                and node.module
                and (
                    node.level
                    or _is_model_module(node.module)
                    or node.module.startswith("ccure_platform.models")
                )
            ):
                for alias in node.names:
                    if alias.name in classes:
                        local[alias.asname or alias.name] = alias.name
        for node in tree.body:
            if isinstance(node, ast.ClassDef) and node.name in classes:
                local[node.name] = node.name

        def foreign(table: str) -> bool:
            owner = owners.get(table)
            return owner is not None and owner not in (cap, "platform")

        for node in ast.walk(tree):
            if isinstance(node, ast.Name) and node.id in local:
                table = classes[local[node.id]]
                if foreign(table):
                    references.add((cap, table))
            if isinstance(node, ast.Call):
                func = node.func
                if isinstance(func, ast.Name) and func.id in local:
                    table = classes[local[func.id]]
                    if foreign(table):
                        writes.add((cap, table))
                name = getattr(func, "id", getattr(func, "attr", None))
                if name in _WRITE_FUNCTIONS and node.args:
                    first = node.args[0]
                    root_name = getattr(first, "id", None) or getattr(
                        getattr(first, "value", None), "id", None
                    )
                    if root_name in local and foreign(classes[local[root_name]]):
                        writes.add((cap, classes[local[root_name]]))
                if (
                    name in {"update", "delete"}
                    and isinstance(func, ast.Attribute)
                    and isinstance(func.value, ast.Call)
                ):
                    inner = func.value
                    while isinstance(inner, ast.Call) and isinstance(
                        inner.func, ast.Attribute
                    ):
                        if inner.func.attr == "query":
                            for arg in inner.args:
                                if isinstance(arg, ast.Name) and arg.id in local:
                                    table = classes[local[arg.id]]
                                    if foreign(table):
                                        writes.add((cap, table))
                            break
                        inner = inner.func.value
        literals = "\n".join(
            n.value
            for n in ast.walk(tree)
            if isinstance(n, ast.Constant) and isinstance(n.value, str)
        )
        for name in _SQL.findall(literals):
            table = name.lower()
            if table in owners and foreign(table):
                references.add((cap, table))
    return references, writes


