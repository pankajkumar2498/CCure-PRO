"""
Audit's capabilities, what each module belongs to, and the ratchet that keeps
the coupling between them from growing.

The module-level ratchets (``layer_rules.py``) hold: no module-level cycle, no
forbidden edge. They cannot see coupling between *capabilities* — every edge is
acyclic file to file while the capabilities as wholes depend on one another.
On 16 Oct 2026, 23 of 27 capabilities formed one strongly connected set
(docs/architecture/MODULE_INDEPENDENCE_ANALYSIS.md). This module measures that,
and ``ratchet_problems`` fails when it grows.

    python -m scripts.architecture.capability_map             # summary
    python -m scripts.architecture.capability_map --json      # every measurement
    python -m scripts.architecture.capability_map --check     # exit 1 on a breach
    python -m scripts.architecture.capability_map --write-baseline

What it ratchets, and what it deliberately does not:

* **Ratcheted** — structural facts: which capabilities form a cycle; every
  module edge that points *up* the target layering or *sideways* between two
  capabilities of one layer; every table a capability references or writes that
  another capability owns; and, for selected entry points, which capabilities
  and heavy third-party packages importing them loads.
* **Not ratcheted** — raw edge counts. A new downward import (a scan engine
  using the check kernel) is the architecture working as intended, and a
  ratchet that failed on it would teach people to regenerate the baseline
  without reading it.

The detail lives in ``capability_baseline.json``, generated by
``--write-baseline``. Its sizes may never exceed ``CEILINGS`` below, which are
the figures measured when the ratchet was introduced and may only be lowered —
so regenerating the baseline cannot quietly admit new coupling.

Static analysis limits, stated rather than hidden:

* an edge is an ``import`` statement — it says a module *can* reach another,
  not that every call path does; lazy (in-function) imports count, because that
  is where this codebase hid its cycles;
* a *write* is detected only as a model construction or a bulk
  ``insert``/``update``/``delete``; assigning to a loaded row's attribute is a
  write too and is counted only as a reference, so write sets are a floor;
* raw SQL is found by table name in string literals, which can miss SQL
  assembled at run time;
* a load profile follows top-level imports from source and ignores
  ``sys.modules`` aliasing; it was checked against real imports in the release
  image on 16 Oct 2026 and agreed to within the alias stubs.

Standard library only: ``scripts/architecture/check.py`` and its pre-commit hook
run this without the backend's dependencies.
"""

