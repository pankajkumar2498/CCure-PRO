/** Official component CSS subset, confined to CCure adapters. No vendor JS/reset. */
import postcss from "postcss";
import { UPSTREAM_DARK_SELECTOR } from "./ux4g-baseline.mjs";

export const COMPONENT_FAMILIES = Object.freeze([
  "btn",
  "icon-btn",
  "input",
  "textarea",
  "select",
  "checkbox",
  "checkmark",
  "radio",
  "radiomark",
  "switch",
  "alert",
  "context-alert",
  "tag",
  "badge",
  "spinner",
  "card",
  "modal",
  "drawer",
  "dropdown",
  "tab",
  "breadcrumb",
  "pagination",
  "page-nav",
  "page-number",
  "page-size",
  "table",
  "navbar",
]);
const component = new RegExp(
  `^\\.ux4g-(?:${COMPONENT_FAMILIES.join("|")})(?:[-\\s.#:[>+~]|$)`,
);
const spinner = /\[class(?:\^|\*)?=["']?(?:ux4g-)?(?:spinner|tag|badge)-/;
const scope = ":where(.cc-ux4g)";

function permitted(selector) {
  // Check the leading component, not an unrelated journey's nested button.
  const leading = selector.startsWith(":")
    ? selector.slice(0, selector.indexOf(")") + 1)
    : selector.split(/[\s>+~]/)[0];
  return (
    ((/^(?:\.ux4g-|:(?:is|where)\(|\[class)/.test(selector) &&
      component.test(leading)) ||
      (/^\[class/.test(selector) && spinner.test(selector))) &&
    !/\.ux4g-(?:input-chip|select-(?:none|text|all|auto))\b/.test(selector)
  );
}

export function componentCss(source, baseline) {
  const tree = postcss.parse(source);
  const animations = new Set();
  const result = postcss.root();
  function extract(container, output) {
    for (const node of container.nodes ?? []) {
      if (node.type === "rule") {
        const selectors = node.selectors.filter(permitted);
        if (!selectors.length) continue;
        const rule = node.clone();
        // The first selector styles an adapter root; the second its descendants.
        // :where keeps upstream specificity. Never emit a global bare selector.
        rule.selectors = selectors.flatMap((s) => [
          `${scope}${s}`,
          `${scope} ${s}`,
        ]);
        rule.walkDecls(/^animation(?:-name)?$/, (d) => {
          for (const name of d.value.match(/ux4g-[a-z0-9-]+/g) ?? [])
            animations.add(name);
        });
        output.append(rule);
      } else if (
        node.type === "atrule" &&
        ["media", "supports", "container"].includes(node.name)
      ) {
        const group = node.clone({ nodes: [] });
        extract(node, group);
        if (group.nodes.length) output.append(group);
      }
    }
  }
  extract(tree, result);
  // Scoped-dark surfaces predate root preferences (notably authentication).
  // Mirror official dark variables on adapters there, preserving that contract.
  // A missing block is an error: skipping it would quietly leave those
  // surfaces on light tokens, which is what an upstream rename used to do.
  let darkBlocks = 0;
  tree.walkRules((rule) => {
    if (rule.selectors.join(",") === UPSTREAM_DARK_SELECTOR) {
      const theme = rule.clone();
      theme.selector = `${scope}:where(.cc-theme-dark),:where(.cc-theme-dark) ${scope}`;
      result.prepend(theme);
      darkBlocks++;
    }
  });
  if (darkBlocks === 0)
    throw new Error(
      `No ${UPSTREAM_DARK_SELECTOR} block in the UX4G source. Upstream restructured its dark theme.`,
    );
  tree.walkAtRules(/keyframes$/, (node) => {
    if (animations.has(node.params)) result.append(node.clone());
  });
  const css = `/* Generated by scripts/build-ux4g-assets.mjs — do not edit.\n * Source: ${baseline.npm.package}@${baseline.npm.version}, scoped CCure adapters only.\n */\n${result.toString()}\n`;
  const problems = componentCssProblems(css);
  if (problems.length) throw new Error(problems.join("\n"));
  for (const family of [
    "btn",
    "input",
    "checkbox",
    "radio",
    "switch",
    "modal",
    "drawer",
    "table",
    "tab",
  ]) {
    if (!css.includes(`.ux4g-${family}`))
      throw new Error(`Missing official component CSS: ${family}`);
  }
  return css;
}

export function componentCssProblems(css) {
  const problems = [];
  const tree = postcss.parse(css);
  tree.walkRules((rule) => {
    if (rule.parent.type === "atrule" && /keyframes$/.test(rule.parent.name))
      return;
    if (
      rule.selectors.some(
        (s) =>
          !s.startsWith(scope) &&
          !s.startsWith(":where(.cc-theme-dark) " + scope),
      )
    )
      problems.push("component CSS escapes the CCure adapter scope");
  });
  tree.walkAtRules((node) => {
    if (
      ![
        "media",
        "supports",
        "container",
        "keyframes",
        "-webkit-keyframes",
      ].includes(node.name)
    )
      problems.push(`unapproved component CSS at-rule: ${node.name}`);
  });
  tree.walkDecls((declaration) => {
    if (
      /url\(/i.test(declaration.value) &&
      !/^.*url\(\s*["']?(?:data:image\/svg\+xml|#)/i.test(declaration.value)
    )
      problems.push("component CSS contains an unapproved asset URL");
    if (/url\(\s*["']?(?:https?:|\/\/|data:font)/i.test(declaration.value))
      problems.push("component CSS contains an external/font URL");
  });
  return [...new Set(problems)];
}
