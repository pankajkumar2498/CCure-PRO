/** Shared build-time asset layout and input identity. No browser runtime. */
import { readFileSync } from "node:fs";
import path from "node:path";
import { FRONTEND_ROOT, readJson, sha256 } from "./ux4g-baseline.mjs";

export const ASSET_LAYOUT = Object.freeze({
  css: "src/design-system/tokens/ux4g.generated.css",
  manifest: "src/design-system/tokens/ux4g.generated.manifest.json",
  fonts: "public/assets/fonts/ux4g",
  publicManifest: "public/assets/ux4g/manifest.json",
  fontUrl: "/assets/fonts/ux4g",
});

export function assetPaths(root = FRONTEND_ROOT) {
  return Object.fromEntries(
    Object.entries(ASSET_LAYOUT)
      .filter(([key]) => key !== "fontUrl")
      .map(([key, file]) => [key, path.join(root, file)]),
  );
}

/** An environment override must never activate unapproved component CSS. */
export function approvedAssetMode(
  baseline,
  requested = process.env.UX4G_CSS_MODE,
) {
  if (baseline.assets.mode !== "tokens" || baseline.runtime.enabled) {
    throw new Error(
      "B.2 approves token/font assets only, with UX4G runtime disabled",
    );
  }
  if (
    requested !== undefined &&
    requested.toLowerCase() !== baseline.assets.mode
  ) {
    throw new Error(
      "UX4G_CSS_MODE differs from the approved token-only pipeline",
    );
  }
  return baseline.assets.mode;
}

/** Hash every implementation/converter input that can affect generated bytes. */
export function pipelineIdentity(root = FRONTEND_ROOT) {
  const scripts = [
    "scripts/build-ux4g-assets.mjs",
    "scripts/ux4g-baseline.mjs",
    "scripts/ux4g-pipeline.mjs",
  ];
  const inputs = Object.fromEntries(
    scripts.map((file) => [file, sha256(readFileSync(path.join(root, file)))]),
  );
  const name = "wawoff2";
  const dir = path.join(root, "node_modules", name);
  const installed = readJson(path.join(dir, "package.json"));
  const locked = readJson(path.join(root, "package-lock.json")).packages?.[
    `node_modules/${name}`
  ];
  if (
    installed.name !== name ||
    installed.version !== locked?.version ||
    !locked?.integrity
  ) {
    throw new Error(
      "WOFF2 converter does not match the locked input; run npm ci",
    );
  }
  const files = Object.fromEntries(
    ["index.js", "compress.js", "build/compress_binding.js"].map((file) => [
      file,
      sha256(readFileSync(path.join(dir, file))),
    ]),
  );
  return {
    schemaVersion: 1,
    inputs,
    converter: {
      package: name,
      version: installed.version,
      integrity: locked.integrity,
      files,
    },
    outputs: ASSET_LAYOUT,
  };
}

/** Reject component/reset CSS and any font source outside the central output. */
export function tokenCssProblems(css, fontFiles) {
  const problems = [];
  const rest = css
    .replace(/\/\*[\s\S]*?\*\//g, "")
    .replace(/@font-face\{[^}]*\}/g, "")
    .replace(/:root(?:\[data-theme=dark\])?\{[^}]*\}/g, "")
    .trim();
  if (rest) problems.push("token pipeline contains component/reset/other CSS");
  const urls = [...css.matchAll(/url\(\s*["']?([^"'\s)]+)["']?\s*\)/g)].map(
    (m) => m[1],
  );
  const expected = fontFiles
    .map((file) => `${ASSET_LAYOUT.fontUrl}/${file}`)
    .sort();
  if (JSON.stringify(urls.sort()) !== JSON.stringify(expected)) {
    problems.push(
      "generated CSS font URLs do not match the central font assets",
    );
  }
  if ((css.match(/@font-face\{/g) ?? []).length !== fontFiles.length) {
    problems.push("generated font-face/file count differs");
  }
  return problems;
}
